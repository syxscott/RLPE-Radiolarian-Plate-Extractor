"""v17 → v18: re-assign panel_id using OCR'd label from each panel image.

The v17 predictions were generated by a pipeline run where the
corner-OCR band was too small to read labels in bandini2011 / other
papers. As a result, 100% of v17 panel_id values fell back to the
caption label list (positional), making pred_id = caption_label[i] but
the IMAGE at panel_NN.png shows a different label (the actual visible
label in the cropped image). Eval F1 was 98.19% but visually the
predictions were wrong.

This script:
  1. Loads the v17 predictions
  2. For each row with a panel_path, OCRs the image to find the
     visible label
  3. Updates the row's panel_id to the OCR'd label
  4. Looks up the species in (parsed_caption, panel_id) for the
     updated panel_id — so the species string follows the
     visible label
  5. Writes v18 predictions

Effect: pred panel_id now matches the actual visible label in
the panel image. Eval F1 will be the *real* F1 (likely lower
than 98.19% but accurate).
"""

