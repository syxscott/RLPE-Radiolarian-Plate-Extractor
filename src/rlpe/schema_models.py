"""Pydantic v2 schema models for the published RLPE output contract.

These models define the *exported* record shape. Internal pipeline code
keeps the existing dataclass types in ``types.py`` (no breaking change
to consumers). At export time, internal ``MatchResult`` is converted to
a :class:`PanelRecord` for JSON Schema validation and downstream use.

Three views are produced by transforming :class:`PanelRecord`:
    - analysis: CSV/Parquet with DwC field names (for paleontologists)
    - ml: JSONL with train/val/test split (for ML researchers)
    - archive: DwC-A zip (for PBDB/GBIF ingest)

The JSON Schema is generated by :func:`emit_json_schema` and published
to ``schemas/rlpe-v1.0.0.json``. Increment ``SCHEMA_VERSION`` whenever
a field is added, removed, or has its semantics changed.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

SCHEMA_VERSION = "1.0.0"

# Strict mode for exported records. ``extra="forbid"`` means a JSONL
# record with an unknown field is rejected, which protects downstream
# consumers from typos in upstream code.
StrictModel = ConfigDict(
    extra="forbid",
    populate_by_name=True,
    str_strip_whitespace=False,  # preserve raw panel labels like "0" vs " 0"
)


class ScaleBarRecord(BaseModel):
    """A scale-bar measurement attached to a panel/figure."""

    model_config = StrictModel
    value: float | None = None
    unit: str | None = None
    source: str | None = None  # "caption" | "ocr" | "image"
    pixel_length: float | None = None
    um_per_px: float | None = None
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    # Phase 61 Plan 4.6 (Bug 4.6): scale_bar sanity check flags
    # 2x-10x disagreement ("scale_bar_disagreement") or drops value on
    # >10x disagreement (value=None, warning="scale_bar_10x_disagreement").
    warning: str | None = None


class GeologyLinkRecord(BaseModel):
    """A geology-fact link associated with a panel's caption context."""

    model_config = StrictModel
    age: str | None = None
    chronostratigraphy: str | None = None
    chronostratigraphy_rank: str | None = None
    # Numeric age interval in Ma, when the chronostratigraphic term can
    # be mapped to an ICS interval. Optional so legacy records remain
    # valid; first-stage exporters may leave these empty.
    ma_top: float | None = None
    ma_base: float | None = None
    ma_mid: float | None = None
    formation: str | None = None
    member: str | None = None
    group: str | None = None
    lithology: str | None = None
    locality: str | None = None
    country: str | None = None
    latitude: float | None = Field(default=None, ge=-90.0, le=90.0)
    longitude: float | None = Field(default=None, ge=-180.0, le=180.0)
    modern_latitude: float | None = Field(default=None, ge=-90.0, le=90.0)
    modern_longitude: float | None = Field(default=None, ge=-180.0, le=180.0)
    paleo_latitude: float | None = Field(default=None, ge=-90.0, le=90.0)
    paleo_longitude: float | None = Field(default=None, ge=-180.0, le=180.0)
    plate_id: str | None = None
    reconstruction_model: str | None = None
    reconstruction_age_ma: float | None = None
    sample_id: str | None = None
    section_type: str | None = None
    section_title: str | None = None
    evidence_text: str | None = None
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    biozone: str | None = None  # optional biozone name (e.g. "N. optima Zone")
    # Phase 63 Plan 6.15 (Bug 6.15): GBIF requires
    # ``coordinateUncertaintyInMeters`` on georeferenced occurrences.
    # Derived from ``coord_source``: regex-extracted -> 1000m, modern
    # centroid -> 25000m, paleodb-derived -> 5000m. ``None`` means
    # the coordinate is missing / not provided.
    coordinate_uncertainty_in_meters: float | None = None
    # Round 24: environment / geochem / facies fields. The
    # radiolarian-extraction user requested these to support
    # Permian–Triassic extinction / recovery studies (P/T
    # boundary, anoxic events, etc.) where the core research
    # question is "when did radiolarians go extinct due to
    # anoxia / acidification / cooling, and when did they
    # recover?". Without these proxies, the data is not
    # geochemically contextualised.
    #
    # Each field is a single keyword from a curated vocabulary
    # (see ``geology_extraction._PALEOENVIRONMENT_VOCAB`` etc.).
    # Round 24 dictionaries are English; the extractor matches
    # case-insensitive. The ``evidence_*`` fields carry the
    # sentence the term was extracted from so the operator can
    # verify the source.
    paleoenvironment: str | None = None  # e.g. "anoxic", "oxic", "upwelling"
    redox: str | None = None  # e.g. "euxinic", "dysoxic", "oxic" (per Algeo & Tribovillard 2009)
    chemostrat: str | None = None  # e.g. "δ13C excursion", "CIE", "TE disaster"
    facies: str | None = None  # e.g. "pelagic", "turbidite", "platform", "basin"
    # Round 22 audit: how the coordinates were derived. Empty string
    # for regex-extracted coords (the default path), ``"country_centroid"``
    # when the Round 21 country-centroid fallback supplied the lat/lon.
    # The frontend / downstream consumers can use this to badge
    # centroid-derived coords.
    coord_source: str = ""


